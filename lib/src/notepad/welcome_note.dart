# Welcome to GPad

Everything you type is saved as you go. There is no Save button, and closing GPad never asks anything.

## Try this

- Press **Ctrl+N** and paste something: code, JSON, an email or a Markdown list. GPad picks Rich, Code or Plain and suggests a name you can change.
- **Ctrl+Shift+V** pastes the clipboard straight into a new note.
- **Ctrl+W** closes a tab. The note stays in the sidebar, so click it to reopen it.
- **Ctrl+Tab** and **Ctrl+Shift+Tab** move between tabs.
- The folder button next to NOTES makes a folder. Drag notes onto it, and their tabs are grouped under the folder's name.
- Right-click a note to move it to another folder or to the trash. Notes stay in the trash for 30 days.
- The palette button changes the theme and code colors.

> Rich notes are Markdown underneath. Switch this note to Code in the status bar to see it.
